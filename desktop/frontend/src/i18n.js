let current = en;
let lang = "en";

/** Picks the language: explicit setting, else the system language. */
export function setLanguage(pref) {
  const sys = (navigator.languages?.[0] || navigator.language || "en").toLowerCase();
  lang = pref || (sys.startsWith("sk") ? "sk" : "en");
  current = lang === "sk" ? { ...en, ...sk } : en;
  document.documentElement.lang = lang;
}

export const language = () => lang;

function pluralKey(n) {
  if (lang === "sk") return n === 1 ? "one" : n >= 2 && n <= 4 ? "few" : "other";
  return n === 1 ? "one" : "other";
}

/** t("key", arg0, arg1…); plural entries pick their form from arg0. */
export function t(key, ...args) {
  let s = current[key] ?? en[key] ?? key;
  if (typeof s === "object") s = s[pluralKey(Number(args[0]))] ?? s.other;
  return s.replace(/\{(\d)\}/g, (_, i) => args[i] ?? "");
}

